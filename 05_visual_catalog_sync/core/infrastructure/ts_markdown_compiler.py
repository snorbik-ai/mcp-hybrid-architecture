#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
========================================================================================
OUTIL INTERNE #05 — VISUAL CATALOG SYNC & TYPESCRIPT COMPILER PIPELINE (CLEAN ARCH)
Couche : Core / Infrastructure (Adaptateur Compilateur TypeScript & Markdown)
========================================================================================
Rôle :
Implémente le port ICatalogArtifactCompilerPort avec responsabilité technique unique :
transformer le dictionnaire JSON du catalogue en un module TypeScript fortement typé
(`RawGlassRailingCatalog.ts`) pour React/Vite ainsi qu'en un inventaire Markdown.
========================================================================================
"""

import os
import json
from typing import Dict, Any
from ..domain.entities_and_ports import ICatalogArtifactCompilerPort


class TypeScriptAndMarkdownCompilerAdapter(ICatalogArtifactCompilerPort):
    """Adaptateur technique de compilation JSON -> TypeScript (.ts) et Markdown (.md)."""

    def compile_typescript_module(
        self,
        catalog_data: Dict[str, Any],
        target_ts_path: str,
    ) -> str:
        os.makedirs(os.path.dirname(os.path.abspath(target_ts_path)), exist_ok=True)
        vignettes = catalog_data.get("category_vignettes", [])
        products = catalog_data.get("products", [])

        ts_code = (
            "// Auto-generated by Outil Interne #05 (visual_catalog_sync_pipeline)\n"
            "export interface RawGlassRailingItem {\n"
            "  sku: string;\n"
            "  title: string;\n"
            "  category_folder: string;\n"
            "  category_label: string;\n"
            "  categories: string[];\n"
            "  price_raw: string;\n"
            "  price_ttc_eur: number | null;\n"
            "  price_ht_eur: number | null;\n"
            "  unit: string;\n"
            "  full_card_text: string;\n"
            "  source_url: string;\n"
            "  image_url: string;\n"
            "  local_image: string;\n"
            "  frontend_public_image: string;\n"
            "}\n\n"
            f"export const RAW_GLASS_RAILING_VIGNETTES = {json.dumps(vignettes, ensure_ascii=False, indent=2)};\n\n"
            f"export const RAW_GLASS_RAILING_PRODUCTS: RawGlassRailingItem[] = {json.dumps(products, ensure_ascii=False, indent=2)};\n\n"
            "// Universal Type Aliases for generic e-commerce consumers\n"
            "export type RawCatalogItem = RawGlassRailingItem;\n"
            "export const RAW_CATALOG_PRODUCTS = RAW_GLASS_RAILING_PRODUCTS;\n"
            "export const RAW_CATALOG_VIGNETTES = RAW_GLASS_RAILING_VIGNETTES;\n"
        )
        with open(target_ts_path, "w", encoding="utf-8") as f:
            f.write(ts_code)
        return os.path.abspath(target_ts_path)

    def compile_markdown_inventory(
        self,
        catalog_data: Dict[str, Any],
        target_md_path: str,
    ) -> str:
        os.makedirs(os.path.dirname(os.path.abspath(target_md_path)), exist_ok=True)
        products = catalog_data.get("products", [])
        vignettes = catalog_data.get("category_vignettes", [])

        by_folder: Dict[str, list] = {}
        for p in products:
            by_folder.setdefault(p.get("category_folder", "other"), []).append(p)

        lines = [
            "# Matière Première — Catalogue Complet Garde-Corps Verre & Accessoires (Réf. InoxDesign)\n",
            f"- **Nombre total de produits & accessoires récupérés** : **{len(products)} références**",
            f"- **Vignettes de catégories récupérées** : **{len(vignettes)} images**",
            "- **Répertoire des images brutes** : `base_src/matiere_premiere_garde_corps_verre/images/`",
            "- **Répertoire public Frontend** : `frontend/public/assets/catalogue_verre/`\n",
        ]

        for folder in sorted(by_folder.keys()):
            items = by_folder[folder]
            lines.append(f"## {folder} ({len(items)} références)\n")
            lines.append("| Réf / SKU | Produit / Accessoire | Prix TTC | Prix HT (est.) | Unité | Image locale | Asset Frontend |")
            lines.append("| :--- | :--- | :--- | :--- | :--- | :--- | :--- |")
            for it in items:
                p_ttc = f"{it['price_ttc_eur']:.2f} €" if it.get("price_ttc_eur") else it.get("price_raw", "Sur devis")
                p_ht = f"{it['price_ht_eur']:.2f} € HT" if it.get("price_ht_eur") else "Sur mesure"
                cats = ", ".join(it.get("categories", []))
                lines.append(
                    f"| `{it.get('sku')}` | **{it.get('title')}**<br/><small>{cats}</small> | **{p_ttc}** | {p_ht} | {it.get('unit')} | `{it.get('local_image')}` | `{it.get('frontend_public_image')}` |"
                )
            lines.append("")

        with open(target_md_path, "w", encoding="utf-8") as f:
            f.write("\n".join(lines))
        return os.path.abspath(target_md_path)
